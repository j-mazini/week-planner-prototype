import { buildInvoiceDocument } from '@/lib/invoice-document';
import type { WorkflowRecord } from '@/lib/invoice-workflow';
import './document.css';

const money = (pence: number) => new Intl.NumberFormat('en-GB', { style: 'currency', currency: 'GBP' }).format(pence / 100);
const day = (date: Date) => new Intl.DateTimeFormat('en-GB', { day: '2-digit', month: '2-digit', year: 'numeric', timeZone: 'UTC' }).format(date);

/**
 * The self-billing invoice as it is issued: A4, letterhead, the days billed,
 * what was deducted and what is left to pay. Reading it is the point — the
 * workflow action lives outside the sheet, so the paper stays paper.
 */
export default function InvoiceDocument({ record }: { record: WorkflowRecord }) {
  const doc = buildInvoiceDocument(record);

  return (
    <article className="idoc" aria-label={`Self billing invoice ${doc.number}`}>
      <header className="idoc-letterhead">
        <div className="idoc-company">
          <img src="/invoice-management/assets/figma-6d3bca1226f092d5.png" alt="" width={32} height={38} />
          <div>
            <p className="idoc-company-name">BA EXPRESS LIMITED</p>
            <p className="idoc-company-line">20 THE LAURELS · INFO@BAEXPRESS.CO.UK · VAT GB238595859</p>
          </div>
        </div>
        <div className="idoc-title">
          <p>SELF BILLING INVOICE</p>
          <strong>{doc.number}</strong>
        </div>
      </header>

      <section className="idoc-parties">
        <div className="idoc-party">
          <h3>VENDOR</h3>
          <dl>
            <div><dt>NAME</dt><dd>{doc.vendor}</dd></div>
            <div><dt>VENDOR ID</dt><dd>{doc.vendorId}</dd></div>
            <div><dt>EMAIL</dt><dd>{doc.email}</dd></div>
          </dl>
        </div>
        <div className="idoc-party">
          <h3>INVOICE</h3>
          <dl>
            <div><dt>INVOICE DATE</dt><dd>{day(doc.issuedDate)}</dd></div>
            <div><dt>DUE DATE</dt><dd>{day(doc.dueDate)}</dd></div>
            <div><dt>PAYMENT TERMS</dt><dd>{doc.terms}</dd></div>
            <div><dt>TOTAL STOPS</dt><dd>{doc.totalStops}</dd></div>
          </dl>
        </div>
      </section>

      <table className="idoc-lines">
        <thead>
          <tr><th scope="col">DATE</th><th scope="col">ROUTE</th><th scope="col">VAT</th><th scope="col" className="idoc-right">AMOUNT</th></tr>
        </thead>
        <tbody>
          {doc.lines.map((line, index) => (
            <tr key={`${line.date.toISOString()}-${index}`}>
              <td>{day(line.date)}</td>
              <td>{line.route}</td>
              <td>{line.vat}</td>
              <td className="idoc-right">{money(line.amount)}</td>
            </tr>
          ))}
          {!doc.lines.length && <tr><td colSpan={4} className="idoc-none">No work billed in this period.</td></tr>}
        </tbody>
      </table>

      <section className="idoc-totals">
        {doc.deductions.length > 0 && (
          <div className="idoc-deductions">
            <h3>DEDUCTIONS</h3>
            {doc.deductions.map(deduction => (
              <p key={deduction.reference}>
                <span>{deduction.label} · {deduction.reference}</span>
                <strong>−{money(deduction.amount)}</strong>
              </p>
            ))}
            <p className="idoc-deductions-total">
              <span>TOTAL DEDUCTIONS</span>
              <strong>−{money(doc.deductionsTotal)}</strong>
            </p>
          </div>
        )}
        <dl className="idoc-summary">
          <div><dt>INVOICE SUBTOTAL</dt><dd>{money(doc.subtotal)}</dd></div>
          <div><dt>VAT</dt><dd>{money(doc.vat)}</dd></div>
          <div className="idoc-summary-total"><dt>INVOICE TOTAL</dt><dd>{money(doc.subtotal + doc.vat)}</dd></div>
        </dl>
      </section>

      <p className="idoc-balance">
        <span>BALANCE DUE · PAYABLE {day(doc.dueDate)}</span>
        <strong>{money(doc.balance)}</strong>
      </p>

      <footer className="idoc-footer">
        <p>
          This is a self-billing invoice issued by BA Express Limited on behalf of the vendor
          under an agreed self-billing arrangement.
        </p>
        <p className="idoc-meta">
          <span>GENERATED BY LOGIX / SPHERE · {day(doc.issuedDate)}</span>
          <span>PAGE 1 OF 1</span>
        </p>
      </footer>
    </article>
  );
}
